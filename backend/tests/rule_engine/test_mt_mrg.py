def test_the_evidence_carries_no_source_paragraphs() -> None:
    # A blunt guard on the licensing boundary: the fixture holds identifiers, digits and
    # digests, so no single string in it is long enough to be a sentence of the guide.
    payload = json.loads(fixture.FIXTURE_PATH.read_text(encoding="utf-8"))
    longest: list[str] = []

    def visit(node: object) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                if key in {"residual", "interpretation", "limitations", "detail"}:
                    continue
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)
        elif isinstance(node, str) and len(node) > 120:
            longest.append(node)

    visit(payload)
    assert not longest, longest[:2]


