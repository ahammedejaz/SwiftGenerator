def test_the_reports_never_claim_certification_or_completeness() -> None:
    # The phrases are allowed to appear — the readiness report exists partly to deny them —
    # but only inside a sentence that denies them. A line that says one of these without a
    # negation is a claim this repository is not entitled to make.
    forbidden = ("swift certified", "fully compliant", "production ready", "conformant")
    denials = ("not ", "never", "no ", "does not")
    for path, body in reports.rendered().items():
        for line in body.lower().splitlines():
            for phrase in forbidden:
                if phrase in line:
                    assert any(word in line for word in denials), (
                        f"{path.name} claims {phrase!r}: {line}"
                    )


