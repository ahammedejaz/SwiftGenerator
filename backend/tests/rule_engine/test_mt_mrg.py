"""Reading a Message Reference Guide, proved without one.

Two halves, deliberately separate.

The first half reads a **synthetic guide this repository owns** — MT999, which does not
exist, with invented rules and invented error codes. It exercises the whole reader end to
end on any machine, which is what makes the pipeline testable at all: the real guides are
licensed and are never committed.

The second half asserts against the **committed evidence fixture** — the derived metadata
the real MT540 and MT541 guides produced. Those assertions are the ones that would catch a
change in what SWIFT actually says, and they need no document either, because everything
they check is a number, an identifier or a digest that was written down when the guides
were read.
"""

