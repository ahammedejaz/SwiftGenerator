def test_a_guide_that_is_present_but_unreadable_is_reported_not_raised(
    tmp_path: Path,
) -> None:
    # The ordinary case is a PDF with no text extractor installed, which is how continuous
    # integration will always see one. Everything derived from the guides is committed, so
    # being unable to re-read them is a condition to report, not a run to abort.
    (tmp_path / "guide.pdf").write_bytes(b"%PDF-1.7\n%not really a pdf\n")
    (tmp_path / "sources.yaml").write_text(
        "sources:\n"
        "  - sourceId: SYNTH-MT-MRG-BROKEN\n"
        "    sourceType: SYNTHETIC_FIXTURE\n"
        "    title: Deliberately unreadable fixture\n"
        '    version: "1.0"\n'
        "    sourceLocation: guide.pdf\n",
        encoding="utf-8",
    )
    outcome = run(MrgSourceCatalogue(tmp_path / "sources.yaml", tmp_path))
    assert outcome.readings == []
    assert outcome.missing == []
    assert [item[0] for item in outcome.unreadable] == ["SYNTH-MT-MRG-BROKEN"]
    assert "SOURCE_" in outcome.unreadable[0][1]
