    if not knowledge_service.indexed:
        lines.append(NOT_AVAILABLE)
        return _normalise(lines)
    rows = _mt_rows()
    preview = [row for row in rows if row.lane != "CONFIGURED"]
    by_release = Counter((row.release, row.readiness) for row in preview)
