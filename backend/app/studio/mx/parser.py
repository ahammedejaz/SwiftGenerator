"""Read an ISO 20022 XML document back into canonical element values.

This is the exact inverse of :mod:`app.studio.mx.generator`'s composer, and it is
deliberately the *only* thing it does. Import produces ``ElementInput`` values — the same
type the JSON API and the Excel importer produce — and then hands them to the ordinary
generation path. There is no second composer, no second validator and no import-only
rendering: a message that has been imported is regenerated by the code that generates every
other message, so the two can never disagree.

The round-trip property the tests hold this to is::

    Compose(Parse(Compose(values))) == Compose(values)

Occurrence numbering is the subtle half. The composer threads a single occurrence index
through each repeatable container down into its non-repeatable descendants, so the parser
has to assign the same index while walking down or the values land in the wrong repeat.

Nothing is silently discarded. An element that is not in the configured subset, a repeat the
subset does not allow, a container holding text, an empty element and a structure the flat
occurrence model cannot represent are each reported as a named issue rather than dropped —
an import that quietly loses half a document is worse than one that refuses.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from xml.etree import ElementTree

from app.studio.models import (
    ElementInput,
    EnvelopeOverride,
    IssueSeverity,
    ValidationIssue,
    ValidationLayer,
)
from app.studio.mx.generator import APPHDR_DEFINITION, APPHDR_NAMESPACE
from app.studio.mx.models import MxElement, MxMessageSpec
from app.studio.mx.registry import MxRegistry, mx_registry

#: The synthetic root used when the pasted text holds two sibling roots — an AppHdr and a
#: Document downloaded separately and concatenated, which is not well-formed XML on its own.
_IMPORT_ROOT = "StudioImportRoot"

_DECLARATION = re.compile(r"^\s*<\?xml[^>]*\?>\s*", re.IGNORECASE)
_TAG = re.compile(r"^(?:\{(?P<ns>[^}]*)\})?(?P<name>.+)$")

#: Maximum accepted input size. Parsing is linear, but an unbounded paste is still a way to
#: spend the server's memory, and no realistic settlement message comes close to this.
MAX_IMPORT_BYTES = 1_000_000


class MxImportError(Exception):
    """The document could not be identified at all, so there is nothing to regenerate."""

    def __init__(self, issue: ValidationIssue) -> None:
        super().__init__(issue.message)
        self.issue = issue


@dataclass
class MxImportResult:
    specification: MxMessageSpec
    elements: list[ElementInput]
    envelope: EnvelopeOverride
    app_hdr_present: bool
    errors: list[ValidationIssue] = field(default_factory=list)
    warnings: list[ValidationIssue] = field(default_factory=list)


def _issue(
    rule_id: str,
    message: str,
    *,
    layer: ValidationLayer = ValidationLayer.CANONICAL,
    severity: IssueSeverity = IssueSeverity.ERROR,
    field_name: str | None = None,
    location: str | None = None,
    expected: str | None = None,
    current: str | None = None,
    suggestion: str | None = None,
) -> ValidationIssue:
    return ValidationIssue(
        rule_id=rule_id,
        severity=severity,
        layer=layer,
        field=field_name,
        location=location,
        message=message,
        expected=expected,
        current_value=current,
        suggestion=suggestion,
    )


def _split_tag(tag: str) -> tuple[str, str]:
    match = _TAG.match(tag)
    if match is None:  # pragma: no cover - ElementTree never produces an empty tag
        return "", tag
    return match.group("ns") or "", match.group("name")


# --------------------------------------------------------------------------------------
# Locating the parts
# --------------------------------------------------------------------------------------


def _load(xml: str) -> ElementTree.Element:
    """Parse the pasted text, tolerating the three shapes a tester can arrive with.

    A wrapped payload, a bare Document, or an AppHdr and a Document downloaded separately
    and pasted one after the other. Only the last needs help: two sibling roots is not a
    well-formed document, so it is wrapped before parsing rather than rejected.
    """
    text = xml.strip()
    if not text:
        raise MxImportError(
            _issue(
                "MX_IMPORT_EMPTY",
                "There is no XML to import.",
                layer=ValidationLayer.XML_WELL_FORMED,
                suggestion="Paste the generated message, or choose a file to upload.",
            )
        )
    if len(text.encode()) > MAX_IMPORT_BYTES:
        raise MxImportError(
            _issue(
                "MX_IMPORT_TOO_LARGE",
                "That document is larger than the studio accepts for import.",
                layer=ValidationLayer.XML_WELL_FORMED,
                expected=f"Up to {MAX_IMPORT_BYTES:,} bytes",
                suggestion="Import one message at a time.",
            )
        )
    try:
        return ElementTree.fromstring(text)
    except ElementTree.ParseError as first_error:
        body = _DECLARATION.sub("", text)
        # Only retry when the input actually looks like markup. Wrapping unconditionally
        # would make plain prose parse as a valid empty root, and the tester would be told
        # their text contained no Document rather than that it was not XML.
        try:
            if not body.lstrip().startswith("<"):
                raise ElementTree.ParseError("not markup")
            return ElementTree.fromstring(f"<{_IMPORT_ROOT}>{body}</{_IMPORT_ROOT}>")
        except ElementTree.ParseError:
            raise MxImportError(
                _issue(
                    "MX_IMPORT_NOT_WELL_FORMED",
                    f"That is not well-formed XML: {first_error}.",
                    layer=ValidationLayer.XML_WELL_FORMED,
                    suggestion="Check for a missing closing tag, and paste the whole message "
                    "including its opening element.",
                )
            ) from first_error


def _find(root: ElementTree.Element, predicate) -> ElementTree.Element | None:  # type: ignore[no-untyped-def]
    """Depth-first search including the root, so any transport wrapper is transparent."""
    if predicate(root):
        return root
    for node in root.iter():
        if predicate(node):
            return node
    return None


def _document_of(
    root: ElementTree.Element, registry: MxRegistry | None = None
) -> tuple[ElementTree.Element, MxMessageSpec]:
    """Identify the message from the document namespace, never from the element name."""
    lookup = registry or mx_registry
    found: list[tuple[ElementTree.Element, MxMessageSpec]] = []
    seen_namespaces: set[str] = set()
    for node in [root, *root.iter()]:
        namespace, _ = _split_tag(node.tag)
        if not namespace.startswith("urn:iso:std:iso:20022:tech:xsd:"):
            continue
        if namespace == APPHDR_NAMESPACE:
            continue
        seen_namespaces.add(namespace)
        spec = lookup.by_namespace(namespace)
        if spec is not None and not any(node is existing for existing, _ in found):
            found.append((node, spec))
            break
    if found:
        return found[0]
    if seen_namespaces:
        raise MxImportError(
            _issue(
                "MX_IMPORT_MESSAGE_NOT_CONFIGURED",
                f"{sorted(seen_namespaces)[0]} is a valid ISO 20022 namespace, but that "
                "message is not configured in this repository.",
                layer=ValidationLayer.STRUCTURE,
                current=sorted(seen_namespaces)[0],
                expected=", ".join(lookup.namespaces()),
                suggestion="Import one of the configured messages, or add the message "
                "specification to backend/config/mx.",
            )
        )
    raise MxImportError(
        _issue(
            "MX_IMPORT_NO_DOCUMENT",
            "No ISO 20022 Document was found in that XML.",
            layer=ValidationLayer.STRUCTURE,
            expected=", ".join(lookup.namespaces()),
            suggestion="Paste the Document element, including its xmlns declaration — the "
            "namespace is what identifies the message.",
        )
    )


