# Document body
# --------------------------------------------------------------------------------------


class _DocumentReader:
    def __init__(self, spec: MxMessageSpec) -> None:
        self._spec = spec
        self._elements: list[ElementInput] = []
        self._errors: list[ValidationIssue] = []
        self._warnings: list[ValidationIssue] = []
        self._claimed: dict[tuple[str, int], str] = {}

    def read(self, document: ElementTree.Element) -> None:
        root_path = f"/{self._spec.document_element}/{self._spec.message_root}"
        children = list(document)
        message_root = None
        for node in children:
            _, name = _split_tag(node.tag)
            if name == self._spec.message_root:
                message_root = node
                break
        if message_root is None:
            self._errors.append(
                _issue(
                    "MX_IMPORT_ROOT_MISMATCH",
                    f"The document does not contain the expected {self._spec.message_root} "
                    "element.",
                    layer=ValidationLayer.STRUCTURE,
                    expected=self._spec.message_root,
                    current=", ".join(_split_tag(node.tag)[1] for node in children) or "nothing",
                    suggestion=f"A {self._spec.message_type} document holds a single "
                    f"{self._spec.message_root} element.",
                )
            )
            return
        self._walk(message_root, self._spec.structure, root_path, occurrence=1)

    @property
    def result(self) -> tuple[list[ElementInput], list[ValidationIssue], list[ValidationIssue]]:
        return self._elements, self._errors, self._warnings

    def _walk(
        self,
        node: ElementTree.Element,
        specification: list[MxElement],
        path: str,
        *,
        occurrence: int,
    ) -> None:
        by_name = {child.name: child for child in specification}
        order = {child.name: index for index, child in enumerate(specification)}
        counts: dict[str, int] = {}
        highest_order = -1
        reported_order = False

        for child_node in node:
            namespace, name = _split_tag(child_node.tag)
            child_path = f"{path}/{name}"
            if namespace and namespace != self._spec.namespace:
                self._errors.append(
                    _issue(
                        "MX_IMPORT_FOREIGN_NAMESPACE",
                        f"'{name}' is in namespace {namespace}, which is not the namespace of "
                        f"{self._spec.message_type}.",
                        layer=ValidationLayer.STRUCTURE,
                        location=child_path,
                        expected=self._spec.namespace,
                        current=namespace,
                        suggestion="Elements of the document must all be in the message "
                        "namespace.",
                    )
                )
                continue
            element = by_name.get(name)
            if element is None:
                self._errors.append(
                    _issue(
                        "MX_IMPORT_UNKNOWN_ELEMENT",
                        f"'{name}' is not part of the configured {self._spec.message_type} "
                        "subset, so its value cannot be imported.",
                        layer=ValidationLayer.STRUCTURE,
                        location=child_path,
                        current=name,
                        expected=", ".join(child.name for child in specification),
                        suggestion="Remove the element, or add it to the message "
                        "specification in backend/config/mx.",
                    )
                )
                continue

            position = order[name]
            if position < highest_order and not reported_order:
                reported_order = True
                self._warnings.append(
                    _issue(
                        "MX_IMPORT_ELEMENT_ORDER",
                        f"The children of {path.rsplit('/', 1)[-1]} are not in specification "
                        "order in the imported document.",
                        layer=ValidationLayer.STRUCTURE,
                        severity=IssueSeverity.WARNING,
                        location=child_path,
                        suggestion="The values were still read. Regenerating writes them back "
                        "in the correct order.",
                    )
                )
            highest_order = max(highest_order, position)

            index = counts.get(name, 0) + 1
            counts[name] = index
            if element.max_occurs > 1:
                child_occurrence = index
            else:
                if index > 1:
                    self._errors.append(
                        _issue(
                            "MX_IMPORT_UNEXPECTED_REPEAT",
                            f"{element.display_name} appears {index} times, but the configured "
                            "subset allows it once.",
                            layer=ValidationLayer.STRUCTURE,
                            field_name=element.display_name,
                            location=child_path,
                            expected="1 occurrence",
                            suggestion="Remove the duplicate, or raise maxOccurs in the "
                            "message specification.",
                        )
                    )
                    continue
                child_occurrence = occurrence

            if element.is_leaf:
                self._read_leaf(child_node, element, child_path, child_occurrence)
            else:
                self._read_container(child_node, element, child_path, child_occurrence)

    def _read_container(
        self,
        node: ElementTree.Element,
        element: MxElement,
        path: str,
        occurrence: int,
    ) -> None:
        text = (node.text or "").strip()
        if text:
            self._errors.append(
                _issue(
                    "MX_IMPORT_TEXT_IN_CONTAINER",
                    f"{element.display_name} is a container but holds the text '{text}'.",
                    layer=ValidationLayer.STRUCTURE,
                    field_name=element.display_name,
                    location=path,
                    current=text,
                    suggestion="Move the value onto one of the child elements.",
                )
            )
        self._walk(node, element.children, path, occurrence=occurrence)

    def _read_leaf(
        self,
        node: ElementTree.Element,
        element: MxElement,
        path: str,
        occurrence: int,
    ) -> None:
        if len(node):
            self._errors.append(
                _issue(
                    "MX_IMPORT_UNEXPECTED_CHILDREN",
                    f"{element.display_name} holds a value in the configured subset, but the "
                    "imported document nests further elements inside it.",
                    layer=ValidationLayer.STRUCTURE,
                    field_name=element.display_name,
                    location=path,
                    current=", ".join(_split_tag(child.tag)[1] for child in node),
                    suggestion="Import a document that matches the configured subset, or "
                    "extend the specification.",
                )
            )
            return

        text = (node.text or "").strip()
        currency = node.get("Ccy")
        if element.currency_attribute and currency:
            # The composer splits "EUR 25000.00" into a Ccy attribute and the bare amount;
            # rejoining them restores the single canonical value a tester typed.
            value = f"{currency} {text}".strip()
        else:
            value = text
            if currency:
                self._warnings.append(
                    _issue(
                        "MX_IMPORT_UNEXPECTED_CURRENCY",
                        f"{element.display_name} carries a Ccy attribute, which the configured "
                        "subset does not define for it. The attribute was not imported.",
                        layer=ValidationLayer.STRUCTURE,
                        severity=IssueSeverity.WARNING,
                        field_name=element.display_name,
                        location=path,
                        current=currency,
                    )
                )

        if not value:
            self._errors.append(
                _issue(
                    "MX_IMPORT_EMPTY_ELEMENT",
                    f"{element.display_name} is present in the document but empty.",
                    layer=ValidationLayer.STRUCTURE,
                    field_name=element.display_name,
                    location=path,
                    suggestion="Give the element a value, or remove it from the document.",
                )
            )
            return

        key = (path, occurrence)
        previous = self._claimed.get(key)
        if previous is not None:
            # Two different repeats resolved to the same (path, occurrence) address. That
            # happens when a repeatable block is nested inside another repeatable block:
            # the flat occurrence index the composer uses cannot tell the two apart, so
            # importing would quietly overwrite one with the other.
            self._errors.append(
                _issue(
                    "MX_IMPORT_NESTED_REPEAT_UNSUPPORTED",
                    f"{element.display_name} occurs inside nested repeating blocks, which this "
                    "platform's element addressing cannot represent.",
                    layer=ValidationLayer.CANONICAL,
                    field_name=element.display_name,
                    location=f"{path}[{occurrence}]",
                    current=value,
                    expected=previous,
                    suggestion="Import a document without repeats nested inside repeats.",
                )
            )
            return
        self._claimed[key] = value
        self._elements.append(ElementInput(path=path, occurrence=occurrence, value=value))


