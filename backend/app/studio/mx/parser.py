def _text_at(node: ElementTree.Element, *names: str) -> str | None:
    """Follow a chain of child names, ignoring namespaces."""
    current: ElementTree.Element | None = node
    for name in names:
        if current is None:
            return None
        current = next(
            (child for child in current if _split_tag(child.tag)[1] == name),
            None,
        )
    if current is None:
        return None
    text = (current.text or "").strip()
    return text or None


def _read_app_hdr(
    spec: MxMessageSpec, header: ElementTree.Element
) -> tuple[EnvelopeOverride, list[ValidationIssue], list[ValidationIssue]]:
    errors: list[ValidationIssue] = []
    warnings: list[ValidationIssue] = []

    definition = _text_at(header, "MsgDefIdr")
    if definition and definition != spec.version:
        errors.append(
            _issue(
                "MX_IMPORT_APPHDR_MISMATCH",
                "The header says this is a different message from the one the document "
                "actually contains.",
                layer=ValidationLayer.APPHDR_CONSISTENCY,
                field_name="Message Definition Identifier (MsgDefIdr)",
                location="/AppHdr/MsgDefIdr",
                expected=spec.version,
                current=definition,
                suggestion="Correct MsgDefIdr, or import the document the header describes.",
            )
        )

    override = EnvelopeOverride(
        sender=_text_at(header, "Fr", "FIId", "FinInstnId", "BICFI"),
        receiver=_text_at(header, "To", "FIId", "FinInstnId", "BICFI"),
        business_message_identifier=_text_at(header, "BizMsgIdr"),
        creation_date=_text_at(header, "CreDt"),
    )
    if _text_at(header, "Sgntr") is not None:
        warnings.append(
            _issue(
                "MX_IMPORT_SIGNATURE_DROPPED",
                "The imported header carries a signature. Signatures are applied by the "
                "messaging infrastructure, so it was read but will not be reproduced.",
                layer=ValidationLayer.APPHDR_CONSISTENCY,
                severity=IssueSeverity.WARNING,
                field_name="Signature (Sgntr)",
                location="/AppHdr/Sgntr",
                suggestion="Regenerating produces an unsigned header, as it always does.",
            )
        )
    return override, errors, warnings


# --------------------------------------------------------------------------------------
# Entry point
# --------------------------------------------------------------------------------------


def parse_message(xml: str, registry: MxRegistry | None = None) -> MxImportResult:
    """Read an ISO 20022 document into canonical element values.

    :raises MxImportError: when the message cannot be identified, which is the only failure
        that leaves nothing to hand to the generator.
    """
    root = _load(xml)
    document, spec = _document_of(root, registry)

    reader = _DocumentReader(spec)
    reader.read(document)
    elements, errors, warnings = reader.result

    header = _find(
        root,
        lambda node: _split_tag(node.tag) == (APPHDR_NAMESPACE, "AppHdr")
        or _split_tag(node.tag)[1] == "AppHdr",
    )
    envelope = EnvelopeOverride()
    if header is not None:
        namespace, _ = _split_tag(header.tag)
        if namespace and namespace != APPHDR_NAMESPACE:
            warnings.append(
                _issue(
                    "MX_IMPORT_APPHDR_VERSION",
                    f"The header uses {namespace}. This platform writes "
                    f"{APPHDR_DEFINITION}, so the regenerated header will use that.",
                    layer=ValidationLayer.APPHDR_CONSISTENCY,
                    severity=IssueSeverity.WARNING,
                    location="/AppHdr",
                    expected=APPHDR_NAMESPACE,
                    current=namespace,
                )
            )
        envelope, header_errors, header_warnings = _read_app_hdr(spec, header)
        errors.extend(header_errors)
        warnings.extend(header_warnings)

    if not elements and not errors:
        errors.append(
            _issue(
                "MX_IMPORT_NO_VALUES",
                "The document was recognised but contains no element values to import.",
                layer=ValidationLayer.CANONICAL,
                suggestion="Check that you pasted the whole message, not just its opening "
                "elements.",
            )
        )

    return MxImportResult(
        specification=spec,
        elements=elements,
        envelope=envelope,
        app_hdr_present=header is not None,
        errors=errors,
        warnings=warnings,
    )
